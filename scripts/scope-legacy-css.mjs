import fs from "node:fs"
import postcss from "postcss"
const [, , themePath, stylePath, outPath] = process.argv
const theme = fs.readFileSync(themePath, "utf8")
const style = fs.readFileSync(stylePath, "utf8")

// ---- theme tokens -> .legacy (light) / .dark .legacy (dark) ----
const t = postcss.parse(theme)
let out = "/* GENERATED by scripts/scope-legacy-css.mjs from dashboard/theme.css + style.css. Scoped under .legacy so it never touches the shadcn UI. */\n"
t.walkRules((rule) => {
  if (rule.parent.type === "atrule" && /prefers-color-scheme/.test(rule.parent.params)) return
  const sel = rule.selector
  let scoped = null
  if (sel === ":root") scoped = ".legacy"
  else if (sel === ':root[data-theme="dark"]') scoped = ".dark .legacy"
  if (!scoped) return
  out += scoped + " {\n" + rule.nodes.map((n) => "  " + n.toString() + ";").join("\n") + "\n}\n"
})

// ---- style.css: prefix every selector ----
const root = postcss.parse(style)
const keep = []
const mapSel = (sel) =>
  sel
    .split(",")
    .map((s) => s.trim())
    .map((s) => {
      if (/^(html|:root)$/.test(s)) return ".legacy"
      if (/^body$/.test(s)) return ".legacy"
      if (/^(html|body)\b/.test(s)) return s.replace(/^(html|body)\s*/, ".legacy ")
      let m
      if ((m = s.match(/^:root\[data-theme="dark"\]\s*(.*)$/))) return ".dark .legacy " + m[1]
      if ((m = s.match(/^:root\[data-theme="light"\]\s*(.*)$/))) return ".legacy " + m[1]
      if (/^:root/.test(s)) return null
      if (/^\*/.test(s)) return ".legacy " + s
      return ".legacy " + s
    })
    .filter(Boolean)
    .join(", ")
function scopeContainer(container) {
  container.each((node) => {
    if (node.type === "rule") {
      if (node.parent.type === "atrule" && /keyframes/.test(node.parent.name)) return
      const next = mapSel(node.selector)
      if (!next) node.remove()
      else {
        node.selector = next
        // rules that were html/body: keep text styling only, never page layout or the page background
        if (next === ".legacy") node.walkDecls((d) => { if (/^(min-height|height|margin|padding|overflow|overflow-x|overflow-y|background|background-image|background-color|background-attachment)$/.test(d.prop)) d.remove() })
      }
    } else if (node.type === "atrule") {
      if (/keyframes|font-face/.test(node.name)) return
      if (/prefers-color-scheme/.test(node.params)) { node.remove(); return }
      if (node.nodes) scopeContainer(node)
    }
  })
}
scopeContainer(root)
out += root.toString()
fs.writeFileSync(outPath, out)
console.log("wrote", outPath, (fs.statSync(outPath).size / 1024).toFixed(0) + " KB")
